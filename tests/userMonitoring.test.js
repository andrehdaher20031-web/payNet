const test = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const { fixture } = require('./helpers/monitoringFixture');
const User = require('../models/User');
const Activity = require('../models/UserActivity');
const Operation = require('../models/UserOperation');
const Payment = require('../models/Payment');
const Alragheb = require('../models/AlraghebTransaction');
const monitoring = require('../services/userMonitoring.service');
const activity = require('../services/userActivity.service');
const FollowUp = require('../models/UserFollowUp');

test('monitoring integration against an isolated database', { timeout: 180000 }, async t => {
  const f = await fixture();
  t.after(f.close);
  const root = '/api/admin/user-monitoring';
  const detail = () => f.request(`${root}/users/${f.buyer._id}`).then(r => r.json());
  await t.test('anonymous, regular user and forged/stale role cannot access private data', async () => {
    for (const path of ['/summary', '/users', '/settings', '/logins', '/export', '/owners', '/analytics', `/users/${f.buyer._id}`, `/users/${f.buyer._id}/activity`, `/users/${f.buyer._id}/journeys`, `/users/${f.buyer._id}/follow-up`]) {
      assert.equal((await f.request(root + path, null)).status, 401);
      assert.equal((await f.request(root + path, f.buyer)).status, 403);
      assert.equal((await f.request(root + path, f.buyer, { headers: { Authorization: `Bearer ${f.token(f.buyer, 'admin')}` } })).status, 403);
    }
    assert.equal((await f.request('/api/admin/all-user', f.buyer)).status, 403);
    assert.equal((await f.request('/api/user', null, { method: 'POST', body: '{}' })).status, 401);
  });
  await t.test('unified operations retain exact SYP, deduplicate provider payments and resolve point transfers', async () => {
    const data = await detail();
    assert.equal(data.stats.count, 6);
    assert.equal(data.stats.purchases, 5);
    assert.equal(data.stats.spent, '529.66');
    assert.equal(data.stats.stalled, 1);
    assert.equal(data.needsAttention, true);
    const source = await Operation.findOne({ key: `payment:${f.completed._id}` }).lean();
    assert.equal(source.sourceModel, 'AlraghebTransaction');
    assert.equal(source.amountSyp, '479.56'); assert.equal(source.quantity, 2000);
    assert.equal(await Operation.countDocuments({ user: f.recipient._id, kind: 'transfer_in' }), 1);
    assert.equal((await User.findById(f.buyer._id)).balance, 479.56);
  });
  await t.test('backfill is repeatable; no fake historic visits and no financial changes', async () => {
    const before = await Operation.countDocuments(), events = await Activity.countDocuments();
    await monitoring.sync({ full: true }); await monitoring.sync({ full: true });
    assert.equal(await Operation.countDocuments(), before);
    assert.equal(await Activity.countDocuments(), events);
    const unknown = await f.request(`${root}/users/${f.unknown._id}`).then(r => r.json());
    assert.equal(unknown.activityStatus, 'unobserved'); assert.equal(unknown.lastSeenAt, undefined);
    const inactive = await f.request(`${root}/users/${f.inactive._id}`).then(r => r.json());
    assert.equal(inactive.activityStatus, 'inactive');
  });
  await t.test('refund and reconciliation update operations but not last visit', async () => {
    const seen = +(await User.findById(f.buyer._id)).lastSeenAt;
    await Alragheb.updateOne({ _id: f.alragheb }, { $set: { status: 'refunded', refundedAt: new Date() } });
    await monitoring.sync();
    const op = await Operation.findOne({ key: `payment:${f.completed._id}` }).lean();
    assert.equal(op.status, 'refunded'); assert.equal(op.refundedSyp, '479.56');
    assert.equal(+(await User.findById(f.buyer._id)).lastSeenAt, seen);
    assert.equal((await detail()).stats.spent, '50.10');
    await Alragheb.updateOne({ _id: f.alragheb }, { $set: { status: 'completed' }, $unset: { refundedAt: 1 } });
    await monitoring.sync();
  });
  await t.test('strict queries, server pagination, filters, export and CSV injection', async () => {
    const response = await f.request(`${root}/users?limit=2`);
    assert.match(response.headers.get('cache-control'), /no-store/);
    const data = await response.json(); assert.equal(data.data.length, 2); assert.equal(data.pagination.total, 5);
    const filtered = await f.request(`${root}/users?activity=inactive`).then(r => r.json()); assert.equal(filtered.pagination.total, 1);
    const searched = await f.request(`${root}/users?search=and@&provider=alragheb`).then(r => r.json()); assert.equal(searched.pagination.total, 1);
    for (const suffix of ['?limit=999', '?search[$ne]=x', '?from=nope', '?page=-1', '?provider=evil', '?from=2026-10-10&to=2026-10-01']) assert.equal((await f.request(`${root}/users${suffix}`)).status, 400);
    assert.equal((await f.request(`${root}/users/invalid`)).status, 400);
    assert.equal((await f.request(`${root}/users/${new mongoose.Types.ObjectId()}`)).status, 404);
    await User.updateOne({ _id: f.unknown._id }, { $set: { name: '=SUM(1,2)' } });
    const csv = await f.request(`${root}/export`).then(r => r.text()); assert.match(csv, /'=SUM/);
    assert.doesNotMatch(csv, /password|never-copy/i);
  });
  await t.test('client events cannot spoof identity, timestamps or financial outcomes', async () => {
    const post = body => f.request('/api/activity/events', f.buyer, { method: 'POST', body: JSON.stringify(body) });
    for (const body of [{ eventType: 'operation_updated' }, { eventType: 'product_view', user: f.admin._id }, { eventType: 'page_view', route: '/?token=secret' }, { eventType: 'product_view', amountSyp: 1000 }, { eventType: 'page_view', occurredAt: new Date().toISOString() }]) assert.equal((await post(body)).status, 400);
    const body = { eventType: 'product_view', provider: 'alragheb', productId: '4', productName: 'SOULHILL CRYSTAL' };
    await Promise.all(Array.from({ length: 5 }, () => post(body)));
    assert.equal(await Activity.countDocuments({ user: f.buyer._id, eventType: 'product_view' }), 1);
    const events = await Activity.find({ eventType: 'product_view' }).lean();
    assert.equal(events[0].source, 'browser');
    assert.ok(+events[0].expiresAt > Date.now() + 179 * 86400000);
    assert.equal((await detail()).interests.find(r => r._id.productId === '4').views, 1);
  });
  await t.test('plain login, old hash migration, login failures and secret redaction', async () => {
    const login = (email, password) => f.request('/api/login', null, { method: 'POST', body: JSON.stringify({ email, password }) });
    assert.equal((await login(f.buyer.email, 'wrong')).status, 401);
    assert.equal((await login('missing@test.invalid', 'wrong')).status, 401);
    assert.equal((await login({ $ne: null }, 'wrong')).status, 400);
    const response = await login(f.buyer.email, 'Test-pass-123'); assert.equal(response.status, 200);
    const payload = await response.json(); assert.ok(payload.token);
    let user = await User.findById(f.buyer._id).select('+password +passwordHash').lean();
    assert.equal(user.password, 'Test-pass-123'); assert.equal(user.passwordHash, undefined); assert.equal(user.loginCount, 1);
    assert.equal(await require('../utils/passwords').verifyPassword('Test-pass-123', user), true);
    assert.ok(user.lastLoginAt);
    const oldHash = await require('../utils/passwords').hashPassword('legacy-test');
    await User.collection.updateOne({ _id: f.unknown._id }, { $set: { passwordHash: oldHash, passwordScheme: 'scrypt' }, $unset: { password: 1 } });
    assert.equal((await login(f.unknown.email, 'legacy-test')).status, 200);
    user = await User.findById(f.unknown._id).select('+password +passwordHash').lean();
    assert.equal(user.password, 'legacy-test'); assert.equal(user.passwordHash, undefined);
    assert.equal(await require('../utils/passwords').verifyPassword('legacy-test', user), true);
    const logins = await f.request(`${root}/users/${f.buyer._id}/logins`).then(r => r.json());
    assert.equal(logins.pagination.total, 2);
    assert.doesNotMatch(JSON.stringify(logins), /Test-pass|legacy-test|passwordHash|Bearer/);
  });
  await t.test('heartbeat throttles writes and background API calls never imply activity', async () => {
    const old = new Date(Date.now() - 180000);
    await User.updateOne({ _id: f.buyer._id }, { $set: { lastSeenAt: old } });
    await f.request('/api/user/balance', f.buyer);
    assert.equal(+(await User.findById(f.buyer._id)).lastSeenAt, +old);
    await f.request('/api/activity/heartbeat', f.buyer, { method: 'POST', body: '{}' });
    const seen = +(await User.findById(f.buyer._id)).lastSeenAt; assert.ok(seen > +old);
    await f.request('/api/activity/heartbeat', f.buyer, { method: 'POST', body: '{}' });
    assert.equal(+(await User.findById(f.buyer._id)).lastSeenAt, seen);
  });
  await t.test('server observes quote and failed purchase without persisting request bodies', async () => {
    await f.request('/api/alragheb/quote', f.buyer, { method: 'POST', body: '{"product_id":4,"password":"never-copy-password"}' });
    await f.request('/api/alragheb/order', f.buyer, { method: 'POST', body: '{}' });
    for (let attempt = 0; attempt < 20 && !await Activity.exists({ eventType: 'request_failed', user: f.buyer._id }); attempt++) await new Promise(resolve => setTimeout(resolve, 25));
    assert.ok(await Activity.exists({ eventType: 'quote_created', user: f.buyer._id, productId: '4' }));
    assert.ok(await Activity.exists({ eventType: 'request_failed', errorCode: 'INSUFFICIENT_BALANCE' }));
    assert.doesNotMatch(JSON.stringify(await Activity.find().lean()), /never-copy/);
    assert.doesNotMatch(JSON.stringify(await Operation.find().lean()), /never-copy/);
  });
  await t.test('settings permissions, validation and summary', async () => {
    assert.equal((await f.request(`${root}/settings`, f.buyer, { method: 'PUT', body: '{}' })).status, 403);
    assert.equal((await f.request(`${root}/settings`, f.admin, { method: 'PUT', body: '{"activeHours":72,"inactiveDays":1}' })).status, 400);
    assert.equal((await f.request(`${root}/settings`, f.admin, { method: 'PUT', body: '{"pendingMinutes":90,"failedThreshold":2}' })).status, 200);
    const summary = await f.request(`${root}/summary`).then(r => r.json());
    assert.equal(summary.total, 5); assert.equal(summary.settings.pendingMinutes, 90);
    assert.ok(summary.needsAttention >= 1);
  });
  await t.test('retention counts purchases only, calculates averages and keeps unknown users unknown', async () => {
    const data = await detail();
    assert.equal(data.retention.successfulPurchases, 2);
    assert.equal(data.retention.segment, 'repeat');
    assert.equal(Number(data.retention.averageOrderSyp), 264.83);
    assert.equal(data.retention.recentPurchases, 2);
    assert.ok(data.favoriteProduct);
    const unknown = await f.request(`${root}/users/${f.admin._id}`).then(r => r.json());
    assert.equal(unknown.retention.risk, 'unknown');
    assert.equal(unknown.retention.averageOrderSyp, null);
    assert.equal(unknown.goal.stage, 'unknown');
  });
  await t.test('intent distinguishes browsing, abandoned, failed, pending and completed purchases', async () => {
    const now = Date.now();
    const user = f.unknown._id;
    const view = { user, provider: 'aleso', productId: 'new-product', productName: 'Intent test', eventType: 'product_view' };
    const goal = () => f.request(`${root}/users/${user}`).then(r => r.json()).then(r => r.goal);
    await activity.record({ ...view, occurredAt: new Date(now - 7200000) });
    assert.equal((await goal()).stage, 'browsing');
    await activity.record({ ...view, eventType: 'checkout_started', occurredAt: new Date(now - 3600000) });
    assert.equal((await goal()).stage, 'abandoned');
    await activity.record({ ...view, eventType: 'checkout_failed', errorCode: 'NETWORK_ERROR', source: 'browser', occurredAt: new Date(now - 1800000) });
    assert.equal((await goal()).stage, 'blocked');
    assert.equal((await goal()).errorCode, 'NETWORK_ERROR');
    const op = await Operation.create({ key: 'intent-test', user, provider: 'aleso', kind: 'purchase', productId: view.productId, productName: view.productName, amountSyp: '25.00', status: 'pending', occurredAt: new Date(now - 600000) });
    assert.equal((await goal()).stage, 'pending');
    await Operation.updateOne({ _id: op._id }, { $set: { status: 'completed' } });
    assert.equal((await goal()).stage, 'completed');
    const filtered = await f.request(`${root}/users?goal=completed&provider=aleso&search=unknown`).then(r => r.json());
    assert.equal(filtered.pagination.total, 1);
    await Activity.deleteMany({ user }); await Operation.deleteOne({ _id: op._id });
  });
  await t.test('high risk and declining purchases use history without financial or credential changes', async () => {
    const now = Date.now(), user = f.inactive._id;
    for (const [index, days] of [50, 49, 48].entries()) await Operation.create({ key: `retention-${index}`, user, provider: 'paynet', kind: 'purchase', status: 'completed', productName: 'Service', amountSyp: '10.00', occurredAt: new Date(now - days * 86400000) });
    const data = await f.request(`${root}/users/${user}`).then(r => r.json());
    assert.equal(data.retention.risk, 'high'); assert.equal(data.purchaseDecline, true);
    assert.ok(data.retention.reasons.includes('purchase_decline'));
    const filtered = await f.request(`${root}/users?risk=high&sort=priority`).then(r => r.json());
    assert.ok(filtered.data.some(row => row._id === String(user)));
    await Operation.deleteMany({ user, key: /^retention-/ });
    assert.equal(await require('../utils/passwords').verifyPassword('Test-pass-123', await User.findById(f.buyer._id).select('+password').lean()), true);
    assert.equal((await User.findById(f.buyer._id)).balance, 479.56);
  });
  await t.test('follow-up validates ownership, persists audit history, rejects lost updates and clears resolved reminders', async () => {
    const path = `${root}/users/${f.buyer._id}/follow-up`;
    const input = { revision: 0, status: 'in_progress', owner: String(f.admin._id), dueAt: new Date(Date.now() - 3600000).toISOString(), confirmedGoal: '=Get monthly subscription', dropOffReason: 'price', note: 'Contacted user about price' };
    const put = (body, user = f.admin) => f.request(path, user, { method: 'PUT', body: JSON.stringify(body) });
    assert.equal((await put(input, f.buyer)).status, 403);
    for (const bad of [{ ...input, owner: String(f.buyer._id) }, { ...input, dueAt: 'bad' }, { ...input, revision: -1 }, { ...input, password: 'unchanged' }, { ...input, note: 'x'.repeat(2001) }]) assert.equal((await put(bad)).status, 400);
    const responses = await Promise.all([put(input), put(input)]);
    assert.deepEqual(responses.map(r => r.status).sort(), [200, 409]);
    const saved = await f.request(path).then(r => r.json());
    assert.equal(saved.history.length, 1); assert.equal(saved.revision, 1); assert.equal(saved.history[0].actor._id, String(f.admin._id));
    const due = await f.request(`${root}/users?due=true&owner=${f.admin._id}&followUp=in_progress`).then(r => r.json());
    assert.equal(due.pagination.total, 1); assert.equal(due.data[0].followUpDue, true);
    const highRisk = await Operation.create({ key: 'due-priority-test', user: f.inactive._id, provider: 'paynet', kind: 'purchase', status: 'completed', productName: 'Service', amountSyp: '10.00', occurredAt: new Date(Date.now() - 60 * 86400000) });
    const priority = await f.request(`${root}/users?sort=priority&limit=2`).then(r => r.json());
    assert.equal(priority.data[0]._id, String(f.buyer._id));
    assert.equal(priority.data[1]._id, String(f.inactive._id));
    await Operation.deleteOne({ _id: highRisk._id });
    const csv = await f.request(`${root}/export?due=true`).then(r => r.text());
    assert.match(csv, /'=Get monthly subscription/);
    assert.equal((await put({ ...input, revision: 1, status: 'resolved', note: 'Resolved' })).status, 200);
    const resolved = await f.request(path).then(r => r.json());
    assert.equal(resolved.dueAt, null); assert.equal(resolved.history.length, 2);
    assert.equal((await f.request(`${root}/users?due=true`).then(r => r.json())).pagination.total, 0);
    await FollowUp.deleteMany({});
  });
  await t.test('journeys split on inactivity and logout, keep order, and exclude admin and history', async () => {
    const user = f.unknown._id, now = Date.now();
    const items = [['page_view', 100], ['product_view', 99], ['checkout_started', 50], ['logout', 49], ['page_view', 48]];
    for (const [eventType, minutes] of items) await activity.record({ user, eventType, source: 'browser', provider: 'paynet', route: '/payinternet', occurredAt: new Date(now - minutes * 60000) });
    await activity.record({ user, eventType: 'admin_action' });
    await activity.record({ user, eventType: 'operation_recorded', source: 'history' });
    const data = await f.request(`${root}/users/${user}/journeys?limit=2`).then(r => r.json());
    assert.equal(data.pagination.total, 3); assert.equal(data.data.length, 2);
    assert.equal(data.data[0].count, 1); assert.equal(data.data[1].count, 2);
    assert.deepEqual(data.data[1].events.map(e => e.eventType), ['checkout_started', 'logout']);
    const second = await f.request(`${root}/users/${user}/journeys?limit=2&page=2`).then(r => r.json());
    assert.equal(second.data[0].count, 2);
    await Activity.deleteMany({ user });
  });
  await t.test('purchase context enriches only the read model and browser failures cannot publish financial outcomes', async () => {
    await activity.record({ user: f.buyer._id, eventType: 'request_accepted', provider: 'paynet', referenceId: String(f.pending._id), productId: 'PHONE', productName: 'Phone bill' });
    await monitoring.sync({ full: true });
    const op = await Operation.findOne({ key: `payment:${f.pending._id}` }).lean();
    assert.equal(op.productId, 'PHONE'); assert.equal(op.productName, 'Phone bill');
    assert.equal((await Payment.findById(f.pending._id)).company, 'Internet');
    const response = await f.request('/api/activity/events', f.buyer, { method: 'POST', body: JSON.stringify({ eventType: 'checkout_failed', provider: 'paynet', productId: 'PHONE', errorCode: 'NETWORK_ERROR' }) });
    assert.equal(response.status, 204);
    assert.equal((await f.request('/api/activity/events', f.buyer, { method: 'POST', body: JSON.stringify({ eventType: 'checkout_failed', provider: 'paynet', productId: 'PHONE', errorCode: 'password=private' }) })).status, 400);
    assert.equal((await Payment.findById(f.pending._id)).status, 'جاري التسديد');
  });
  await t.test('analytics counts distinct users, excludes transfers and reports unknown rates on empty data', async () => {
    for (const days of [45, 37, 14]) await activity.record({ user: f.inactive._id, source: 'browser', eventType: 'page_view', route: '/', occurredAt: new Date(Date.now() - days * 86400000) });
    await activity.record({ user: f.admin._id, source: 'browser', eventType: 'page_view', route: '/', occurredAt: new Date(Date.now() - 45 * 86400000) });
    const data = await f.request(`${root}/analytics`).then(r => r.json());
    assert.equal(data.purchases.count, 2); assert.equal(data.purchases.users, 1);
    assert.equal(data.repeatPurchaseRate, 100);
    assert.equal(Number(data.purchases.spent), 529.66);
    assert.ok(data.days.length > 0);
    const cohort = data.cohorts.find(row => row.eligible30 > 0);
    assert.equal(cohort.eligible7, 1); assert.equal(cohort.rate7, 100);
    assert.equal(cohort.eligible30, 1); assert.equal(cohort.rate30, 100);
    const owners = await f.request(`${root}/owners`).then(r => r.json());
    assert.equal(owners.length, 1); assert.equal(owners[0]._id, String(f.admin._id));
    assert.doesNotMatch(JSON.stringify(owners), /password/);
    await Operation.deleteMany({});
    const empty = await f.request(`${root}/analytics`).then(r => r.json());
    assert.equal(empty.repeatPurchaseRate, null); assert.equal(empty.purchases.users, 0);
  });
});
